export type MessageKey = keyof typeof en;
const CATALOGUE: Record<Locale, Messages> = { en, ar };

/** Translate a key, interpolating {placeholders}. */
export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = CATALOGUE[locale][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Translate a dynamic key (e.g. from an API message_key), with a fallback key. */
export function tDynamic(
  locale: Locale,
  key: string,
  fallback: MessageKey,
  vars?: Record<string, string | number>,
): string {
  return key in CATALOGUE[locale] ? t(locale, key as MessageKey, vars) : t(locale, fallback, vars);
}

export function hasKey(key: string): key is MessageKey {
  return key in en;
}

export function catalogueKeys(locale: Locale): string[] {
  return Object.keys(CATALOGUE[locale]).sort();
}

/** Display timestamps in Asia/Dubai; storage and API stay UTC (CLAUDE.md). */
export function formatDubaiTime(iso: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-AE' : 'en-AE', {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone: 'Asia/Dubai',
  }).format(new Date(iso));
}

/** Calendar dates (YYYY-MM-DD) are shown as dates without time-zone shifting. */
export function formatDate(isoDate: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-AE' : 'en-AE', {
    dateStyle: 'medium',
    timeZone: 'UTC',
  }).format(new Date(`${isoDate}T00:00:00Z`));
}
